/**
 * The NOAA notice in the native apps' notices (scripts/native/third-party-notices.mjs).
 *
 * src/world/wmm<year>-coefficients.ts holds the World Magnetic Model's coefficients, and NOAA's NCEI asks for a notice
 * (17 U.S.C. 403) with a work that includes the model's U.S. Government material. The repository's documents carry it
 * (NOTICE.md, THIRD_PARTY.md), but the notices an app carries are generated for exactly what its bundle contains, and
 * nothing else would have put the NOAA notice into one. So a bundle whose module list includes the coefficient module
 * carries the notice, in the words the generated module's header holds (scripts/gen-wmm-coefficients.mjs writes them
 * once), and a bundle that does not include it carries nothing about the model.
 *
 * Run: npm run test:wave (every wp-*.test.ts), or node --experimental-strip-types --no-warnings --test <this file>
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  WMM_MODULE,
  bundleNotices,
  bundledDataNotices,
  componentsWithoutText,
  renderNotices,
  wmmNotice,
} from '../../../scripts/native/third-party-notices.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..')
const MODULE_FILE = readdirSync(join(ROOT, 'src', 'world')).find((name) => /^wmm\d{4}-coefficients\.ts$/.test(name))!
const MODULE_SOURCE = readFileSync(join(ROOT, 'src', 'world', MODULE_FILE), 'utf8')

type Entry = { component: { group: string; name: string; licence: string; source: string }; texts: string[] }
const entries = bundledDataNotices as unknown as (modules: string[], root?: string) => Entry[]
const notice = wmmNotice as unknown as (source: string) => string | null

test('the notice is the generated header\'s paragraph, whole, as one line of words', () => {
  assert.ok(MODULE_FILE, 'the repository has a generated coefficient module')
  const text = notice(MODULE_SOURCE)
  assert.ok(text, 'the header carries a notice')
  assert.match(text, /^Notice \(17 U\.S\.C\. 403\): /)
  assert.ok(text.includes('World Magnetic Model'))
  assert.ok(text.includes('public domain and not licensed or under copyright'), "NCEI's own statement")
  assert.ok(text.includes('consist predominantly of the model\'s U.S. Government material'), "NCEI's condition, as NCEI states it")
  assert.ok(text.includes('as 17 U.S.C. 403 requires') && text.includes('must give notice'), "NCEI's statement of what the Act requires, said as NCEI's")
  assert.ok(text.includes('not subject to copyright protection'), 'the statement NCEI asks a notice to make')
  assert.ok(text.includes('https://www.ncei.noaa.gov/products/world-magnetic-model'), 'where the notice comes from')
  assert.doesNotMatch(text, /\n| \* |\*\//, 'no line breaks and no comment marks of the header it was read from')
  assert.ok(!text.includes('SHA-256') && !text.includes('Browser-safe'), 'the paragraph and nothing around it')
})

test('a header with no notice gives none: the notices are not made from it', () => {
  assert.equal(notice('export const WMM_EPOCH = 2025\n'), null)
  assert.equal(notice('/**\n * GENERATED by scripts/gen-wmm-coefficients.mjs.\n *\n * Nothing else.\n */\n'), null)
  assert.equal(notice(MODULE_SOURCE.replace('Notice (17 U.S.C. 403)', 'Remark')), null)
})

test('the module is found by the id a bundle report gives it, and only that module', () => {
  const matches = (id: string) => WMM_MODULE.test(id)
  assert.ok(matches('/home/build/repo/src/world/wmm2025-coefficients.ts'))
  assert.ok(matches('/repo/src/world/wmm2030-coefficients.ts'))
  assert.ok(matches('src/world/wmm2025-coefficients.ts'))
  for (const id of ['/repo/src/world/declination.ts', '/repo/src/world/wmm25-coefficients.ts', '/repo/src/other/wmm2025-coefficients.ts',
    '/repo/src/world/wmm2025-coefficients.ts.map', '/repo/node_modules/wmm2025-coefficients.ts', '/repo/src/world/awmm2025-coefficients.ts']) {
    assert.ok(!matches(id), id)
  }
})

test('a bundle that includes the coefficients owes the notice, with the words of the module, and one that does not owes nothing', () => {
  assert.deepEqual(entries([]), [])
  assert.deepEqual(entries(['/repo/src/world/declination.ts', '/repo/node_modules/three/build/three.module.js', '/repo/src/world/geo.ts']), [])
  for (const id of [`/home/build/repo/src/world/${MODULE_FILE}`, `C:\\repo\\src\\world\\${MODULE_FILE}`]) {
    const owed = entries(['/repo/src/main.ts', id])
    assert.equal(owed.length, 1, id)
    const [one] = owed
    assert.equal(one!.component.group, 'vendored')
    assert.match(one!.component.name, new RegExp(`^World Magnetic Model WMM\\d{4} coefficients \\(NOAA NCEI\\), in src/world/${MODULE_FILE.replace('.', '\\.')}$`))
    assert.match(one!.component.licence, /^Public domain \(U\.S\. Government material, 17 U\.S\.C\. 403\)$/)
    assert.equal(one!.component.source, 'https://www.ncei.noaa.gov/products/world-magnetic-model')
    assert.deepEqual(one!.texts, [notice(MODULE_SOURCE)])
  }
})

test('the generated notices carry it when the bundle includes the coefficients, each in its place, and nothing about it when not', {
  skip: ['node_modules/onnxruntime-web', 'node_modules/three'].filter((path) => !existsSync(join(ROOT, path))).join(', ') || false,
}, () => {
  type Generated = { components: Array<{ group: string; name: string; texts: string[] }>; texts: Record<string, string> }
  const make = bundleNotices as unknown as (options: { shell: 'desktop'; bundledModules: string[]; targets: string[] }) => Generated
  const without = make({ shell: 'desktop', bundledModules: [], targets: [] })
  assert.ok(!without.components.some((c) => c.name.includes('World Magnetic Model')), 'a bundle without the data lists nothing about it')
  const withData = make({ shell: 'desktop', bundledModules: [`/repo/src/world/${MODULE_FILE}`], targets: [] })
  const listed = withData.components.filter((c) => c.name.includes('World Magnetic Model'))
  assert.equal(listed.length, 1)
  assert.equal(listed[0]!.group, 'vendored')
  assert.deepEqual(listed[0]!.texts.map((id) => withData.texts[id]), [notice(MODULE_SOURCE)])
  assert.deepEqual(componentsWithoutText(withData), [], 'it has its text, so the notices are made')
  // As THIRD-PARTY-NOTICES.txt prints it: the component under the heading of those no package manager lists, the notice under its name.
  const printed = renderNotices(withData, '0.0.0')
  assert.ok(printed.includes(`\n---- Applies to: ${listed[0]!.name}\n\n${notice(MODULE_SOURCE)}\n`), 'the notice is printed under the name of the data it is for')
  assert.ok(printed.indexOf(listed[0]!.name) > printed.indexOf('== Components no package manager lists =='))
  assert.ok(printed.indexOf(listed[0]!.name) < printed.indexOf('== Licence texts =='))
  assert.ok(!renderNotices(without, '0.0.0').includes('World Magnetic Model'))
})

test('a bundle with the module whose header lost its notice is not made: the data does not ship without it', () => {
  const dir = mkdtempSync(join(tmpdir(), 'wmm-notice-'))
  try {
    mkdirSync(join(dir, 'src', 'world'), { recursive: true })
    const id = `/repo/src/world/${MODULE_FILE}`
    writeFileSync(join(dir, 'src', 'world', MODULE_FILE), MODULE_SOURCE.replace('Notice (17 U.S.C. 403)', 'Remark'))
    assert.throws(() => entries([id], dir), /src\/world\/wmm\d{4}-coefficients\.ts is in the bundle but its header has no "Notice \(17 U\.S\.C\. 403\)" paragraph/)
    writeFileSync(join(dir, 'src', 'world', MODULE_FILE), MODULE_SOURCE)
    assert.equal(entries([id], dir).length, 1, 'the same module with its notice is bundled')
    assert.equal(entries(['/repo/src/main.ts'], dir).length, 0, 'a bundle without the module needs no file of it')
    // The next model's module is found by its own name, and the component is named for it.
    writeFileSync(join(dir, 'src', 'world', 'wmm2031-coefficients.ts'), MODULE_SOURCE)
    const [next] = entries(['/repo/src/world/wmm2031-coefficients.ts'], dir)
    assert.equal(next!.component.name, 'World Magnetic Model WMM2031 coefficients (NOAA NCEI), in src/world/wmm2031-coefficients.ts')
    // A bundle that holds two (while one model gives way to the next) owes a notice for each, once each, however often the id is listed.
    const both = entries([id, '/repo/src/world/wmm2031-coefficients.ts', id, '/repo/src/main.ts'], dir)
    assert.deepEqual(both.map((e) => e.component.name.match(/WMM\d{4}/)![0]), [MODULE_FILE.slice(0, 7).toUpperCase(), 'WMM2031'].sort())
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
  // The hook: bundleNotices adds it with the other components, so every bundle goes through it.
  const source = readFileSync(join(ROOT, 'scripts/native/third-party-notices.mjs'), 'utf8').replace(/\r\n/g, '\n')
  const build = source.slice(source.indexOf('export function bundleNotices'))
  assert.match(build, /addVendored\(notices, shell, targets\)\n {2}addBundledData\(notices, bundledModules\)\n {2}addNpmPackages\(notices, bundledModules\)/)
})

test('NOTICE.md and THIRD_PARTY.md say the apps carry the notice with the data', () => {
  for (const file of ['NOTICE.md', 'THIRD_PARTY.md']) {
    const text = readFileSync(join(ROOT, file), 'utf8').replace(/\s+/g, ' ')
    assert.ok(text.includes('THIRD-PARTY-NOTICES.txt'), file)
  }
  assert.ok(readFileSync(join(ROOT, 'NOTICE.md'), 'utf8').replace(/\s+/g, ' ').includes('carries this notice whenever its bundle includes the coefficients'))
})
