/**
 * The tag family: 5x5 data cells inside a one-cell black border, 32 ids, every pair of
 * (id, rotation) at least 9 bits apart.
 *
 * ## Where the codes come from
 *
 * Generated, not hand-picked: `searchFamily()` in `./dictionary-search.ts` draws random 25-bit
 * words from a seeded PRNG (`mulberry32`, already in the repo) and keeps a word only when it is at
 * least `minDistance` bits from every rotation of every word already kept, and from its OWN other
 * rotations (so a code can never be read as itself turned a quarter, which is what pins the tag's
 * orientation). The table below is that search's output, frozen so nothing is computed at load;
 * `tests/unit/node/fiducial_dictionary.test.ts` re-runs the search and fails if the table drifts
 * from it. Regenerate by running the search with `CSCAN5_V1_PARAMS` and pasting the result.
 *
 * `minDistance` on the exported dictionary is COMPUTED from the table when it is built
 * (`createDictionary`), never declared: the generator's constraint and the table's property are
 * checked against each other by the same test.
 *
 * The search also keeps every code at least `minMirrorDistance` bits from the MIRROR IMAGES of every
 * code, itself included. A tag seen in a mirror, through glass, or printed on thin paper and read from
 * behind is the pattern flipped left to right, and a code that is its own mirror image (one in
 * four of the codes the first version of this table drew at random came close) would be read as itself
 * with its corners in the wrong order. With the mirror distance at 5, a mirrored tag is refused at every
 * bit-error ceiling up to the correctable limit of 4.
 *
 * ## Why it is not tag36h11 or an ArUco dictionary, and what swapping one in means
 *
 * Those families are not reproduced here. Their code tables are published data this package may
 * not fetch (no network, no new dependency, no downloaded data in WP-14a), and copying tables from
 * another project is exactly what a clean-room build has to avoid. So this is an open family of
 * our own: it decodes only tags generated by `scripts/print-fiducial.mjs`, and a tag printed for
 * AprilTag or ArUco software will (correctly) not decode here.
 *
 * Nothing in the detector depends on this particular family. The detector samples a
 * `bits x bits` grid of black/white cells inside a one-cell black border (the layout tag36h11,
 * tag25h9, tag16h5 and every ArUco dictionary share) and asks a `Dictionary` to name it. Swapping
 * in a standard family later means writing a `Dictionary` whose `match()` knows that family's
 * words, and nothing else:
 *
 *   - families of up to 32 data bits (4x4, 5x5): call `createDictionary(name, bits, words)` with
 *     the family's words in the bit order documented there;
 *   - 36-bit families (tag36h11 has a 6x6 grid): the word does not fit a 32-bit integer, so
 *     implement `match()` over two halves (or BigInt) instead of reusing `createDictionary`;
 *   - note AprilTag draws its tags with a white ring OUTSIDE the black one that is part of the
 *     tag; here that white ring is the quiet zone, and the detector requires one (see
 *     `scripts/print-fiducial.mjs`).
 *
 * The printed sheet records the family name in its QR payload, so a sheet printed for one family
 * is never mistaken for another's.
 *
 * ## Bit layout
 *
 * A word's bit `r * bits + c` (least significant bit first) is the data cell in row `r`, column
 * `c`, counted from the printed top-left of the data region. A SET bit is a BLACK cell.
 */
import type { Dictionary, DictionaryMatch, QuarterTurns } from './types.ts'

/** Number of set bits in a 32-bit word. */
export function popcount32(x: number): number {
  let v = x >>> 0
  v -= (v >>> 1) & 0x55555555
  v = (v & 0x33333333) + ((v >>> 2) & 0x33333333)
  v = (v + (v >>> 4)) & 0x0f0f0f0f
  return Math.imul(v, 0x01010101) >>> 24
}

/**
 * Turn a `bits x bits` pattern a quarter turn clockwise: the cell at (row r, column c) moves to
 * (row c, column bits - 1 - r). The top-left cell goes to the top-right, which is what a tag
 * whose printed top-left corner sits at the quad's second corner looks like.
 */
export function rotateWordClockwise(word: number, bits: number): number {
  let out = 0
  for (let r = 0; r < bits; r++) {
    for (let c = 0; c < bits; c++) {
      if ((word >>> (r * bits + c)) & 1) out |= 1 << (c * bits + (bits - 1 - r))
    }
  }
  return out >>> 0
}

/** A pattern mirrored left to right: the cell at (row r, column c) moves to (row r, column bits - 1 - c). */
export function flipWord(word: number, bits: number): number {
  let out = 0
  for (let r = 0; r < bits; r++) {
    for (let c = 0; c < bits; c++) {
      if ((word >>> (r * bits + c)) & 1) out |= 1 << (r * bits + (bits - 1 - c))
    }
  }
  return out >>> 0
}

/** The four clockwise rotations of a pattern: index k is the pattern turned k quarter turns. */
export function wordRotations(word: number, bits: number): [number, number, number, number] {
  const r1 = rotateWordClockwise(word, bits)
  const r2 = rotateWordClockwise(r1, bits)
  const r3 = rotateWordClockwise(r2, bits)
  return [word >>> 0, r1, r2, r3]
}

/**
 * The smallest Hamming distance between two distinct (word, rotation) pairs of a family,
 * including a word against its own other rotations. Turning both words by the same amount does
 * not change their distance, so it is enough to compare one word as printed against the other in
 * all four rotations.
 */
export function familyMinDistance(words: readonly number[], bits: number): number {
  const rotated = words.map((w) => wordRotations(w, bits))
  let min = Infinity
  for (let a = 0; a < words.length; a++) {
    for (let b = a; b < words.length; b++) {
      for (let k = a === b ? 1 : 0; k < 4; k++) {
        const d = popcount32(words[a]! ^ rotated[b]![k]!)
        if (d < min) min = d
      }
    }
  }
  return min
}

/**
 * The smallest Hamming distance between the mirror image of a word, in any of its four turns, and any word of
 * the family as printed, the word itself included (a code that is its own mirror image is at distance 0).
 */
export function familyMinMirrorDistance(words: readonly number[], bits: number): number {
  let min = Infinity
  for (const a of words) {
    const mirrored = wordRotations(flipWord(a, bits), bits)
    for (const b of words) {
      for (const m of mirrored) {
        const d = popcount32(m ^ b)
        if (d < min) min = d
      }
    }
  }
  return min
}

/**
 * Build a dictionary from a table of words (`bits * bits <= 32`, bit order in the file header).
 * Throws on a table that is not a usable family: duplicate words, words wider than the grid, or
 * a word that equals one of its own rotations.
 */
export function createDictionary(name: string, bits: number, words: readonly number[]): Dictionary {
  const cells = bits * bits
  if (!Number.isInteger(bits) || bits < 2 || cells > 32) {
    throw new Error(`dictionary ${name}: a ${bits}x${bits} grid does not fit a 32-bit word`)
  }
  const limit = cells === 32 ? 0x100000000 : 2 ** cells
  const seen = new Set<number>()
  for (const w of words) {
    if (!Number.isInteger(w) || w < 0 || w >= limit) throw new Error(`dictionary ${name}: ${w} is not a ${cells}-bit word`)
    if (seen.has(w)) throw new Error(`dictionary ${name}: word ${w} appears twice`)
    seen.add(w)
  }
  if (words.length < 2) throw new Error(`dictionary ${name}: needs at least two ids`)

  const minDistance = familyMinDistance(words, bits)
  if (minDistance < 1) throw new Error(`dictionary ${name}: two codes are the same pattern once rotated`)
  const minMirrorDistance = familyMinMirrorDistance(words, bits)
  const rotated = words.map((w) => wordRotations(w, bits))

  return {
    name,
    bits,
    size: words.length,
    minDistance,
    maxCorrectableBits: Math.floor((minDistance - 1) / 2),
    minMirrorDistance,

    pattern(id: number): Uint8Array {
      const word = words[id]
      if (word === undefined) throw new RangeError(`dictionary ${name}: no id ${id}`)
      const out = new Uint8Array(cells)
      for (let i = 0; i < cells; i++) out[i] = (word >>> i) & 1
      return out
    },

    match(observed: ArrayLike<number>, maxHamming: number): DictionaryMatch | null {
      if (observed.length !== cells) return null
      let word = 0
      for (let i = 0; i < cells; i++) if (observed[i]) word |= 1 << i
      word >>>= 0

      let bestD = Infinity
      let bestId = -1
      let bestK = 0
      let secondD = Infinity
      for (let id = 0; id < rotated.length; id++) {
        const r = rotated[id]!
        for (let k = 0; k < 4; k++) {
          const d = popcount32(word ^ r[k]!)
          if (d < bestD) {
            secondD = bestD
            bestD = d
            bestId = id
            bestK = k
          } else if (d < secondD) {
            secondD = d
          }
        }
      }
      if (bestD > maxHamming) return null
      // Two readings within reach of the same grid: refuse rather than pick one. Unreachable while
      // maxHamming <= maxCorrectableBits, which is what makes that a safe ceiling.
      if (secondD <= maxHamming) return null
      return { id: bestId, rotation: bestK as QuarterTurns, hamming: bestD }
    },
  }
}

